import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1280, height: 900 } })
p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE ERROR:', m.text()) })
await p.goto('http://localhost:4079')
await p.waitForTimeout(700)
await p.getByText('Peace & Quiet').click()
await p.getByRole('button', { name: 'Continue' }).click()
await p.waitForTimeout(500)
await p.getByLabel('Start date').fill('2026-12-20')
await p.getByLabel('End date').fill('2026-12-27')
await p.getByLabel(/Total budget/).fill('250000')
await p.getByLabel('Travellers').fill('4')
await p.getByLabel('Flying from').selectOption({ label: 'Mumbai' })
await p.getByRole('button', { name: 'Continue' }).click()
await p.waitForTimeout(700)
await p.getByRole('button', { name: /Within India/ }).click()
await p.waitForTimeout(800)
console.log('=== Q2 ===')
console.log(await p.locator('body').innerText())
await p.screenshot({ path: '.agency/screenshots/anita-05-q2.png', fullPage: true })
await b.close()
